class 陪伴型宠物情绪引擎:
    def __init__(self) -> None:
        self.当前稳定情绪 = 默认状态['情绪']
        self.当前稳定文案 = 默认状态['文案']
        self.当前来源 = 默认状态['来源']
        self.当前情绪开始时间 = 0.0
        self.最近执行结束时间 = 0.0
        self.最近执行活跃时间 = 0.0
        self.上次关心时间 = 0.0  # 上次主动关心用户的时间
        self.上次签名 = ''
        self.上次结果: 情绪决策 | None = None
        self.情绪记忆: dict[str, float] = {情绪: 0.0 for 情绪 in 允许情绪}  # 情绪记忆，影响连续性
        self.空闲链 = ['待机中', '调皮中', '等待回复中', '好奇中', '待机中']
        self.交互情绪 = {'倾听中', '思考中', '执行中', '开心中', '得意中', '心疼中', '需注意'}

    def 读取会话快照(self) -> 会话快照:
        会话信息: dict[str, Any] = {}
        会话文件: Path | None = None
        if 会话存储文件.exists():
            try:
                索引 = json.loads(会话存储文件.read_text(encoding='utf-8'))
                if isinstance(索引, dict):
                    会话信息 = 索引.get(目标会话键, {}) or {}
                    路径 = 会话信息.get('sessionFile')
                    if 路径:
                        会话文件 = Path(str(路径))
            except (OSError, json.JSONDecodeError):
                会话信息 = {}
        消息列表 = self._读取消息列表(会话文件)
        return 会话快照(会话信息=会话信息, 消息列表=消息列表, 最后更新时间=self._提取更新时间(会话信息))

    def 决策(self, 快照: 会话快照, 当前时间: float | None = None) -> 情绪决策:
        当前时间 = 当前时间 or time.time()
        注入状态 = 读取情绪注入()
        if 注入状态:
            return 情绪决策(情绪=注入状态['情绪'], 文案=注入状态['文案'], 来源='手动注入', 分数={注入状态['情绪']: 99.0})

        签名 = self._构建签名(快照)
        if 签名 == self.上次签名 and self.上次结果 is not None:
            return self.上次结果

        分数 = {情绪: 0.0 for 情绪 in 允许情绪}
        线索 = self._提取线索(快照, 当前时间)
        来源 = self._叠加真实行为层(分数, 线索)
        推断情绪 = self._消息驱动情绪推断(线索)
        if 推断情绪:
            分数[推断情绪] += 8.8
            if 来源 == '自动判断':
                来源 = '消息推断'
        self._叠加会话氛围层(分数, 线索)
        self._叠加时间节律层(分数, 线索, 当前时间)
        self._叠加执行尾声层(分数, 线索, 当前时间)
        self._叠加陪伴修饰层(分数, 线索)

        if max(分数.values()) <= 0:
            分数['待机中'] += 3.0

        是否触发关心, 关心来源 = self._叠加主动关心层(分数, 线索, 当前时间)
        self._叠加搞定感层(分数, 线索)
        self._叠加情绪记忆层(分数, 当前时间)

        情绪 = max(分数, key=分数.get)
        文案 = self._生成文案(情绪, 线索, 当前时间)
        if 是否触发关心 and 关心来源:
            文案 = 关心来源

        执行中工具 = 线索.get('当前执行工具', '')
        执行步骤 = ''
        当前步骤 = 线索.get('执行步骤', 0)
        总步骤 = 线索.get('工具调用次数', 0)
        if 当前步骤 > 0 and 总步骤 > 0:
            执行步骤 = f'第{当前步骤}步/共{总步骤}步'

        结果 = 情绪决策(情绪=情绪, 文案=文案, 来源=来源, 分数=分数, 执行中工具=执行中工具, 执行步骤=执行步骤)
        self.上次签名 = 签名
        self.上次结果 = 结果
        return 结果

    def 应用防抖(self, 决策结果: 情绪决策, 当前时间: float | None = None) -> tuple[str, str, str]:
        当前时间 = 当前时间 or time.time()
        候选情绪 = 决策结果.情绪
        候选文案 = 决策结果.文案
        候选来源 = 决策结果.来源

        if self.当前情绪开始时间 == 0.0:
            self._切换到(候选情绪, 候选文案, 候选来源, 当前时间)
            return self.当前稳定情绪, self.当前稳定文案, self.当前来源

        if 候选情绪 == self.当前稳定情绪:
            self.当前稳定文案 = 候选文案
            self.当前来源 = 候选来源
            return self.当前稳定情绪, self.当前稳定文案, self.当前来源

        当前分 = 决策结果.分数.get(self.当前稳定情绪, 0.0)
        候选分 = 决策结果.分数.get(候选情绪, 0.0)
        已停留 = 当前时间 - self.当前情绪开始时间
        最短停留 = 最短停留秒数.get(self.当前稳定情绪, 6.0)
        足够强 = 候选分 >= 当前分 + 3.2
        高优先级 = 候选来源 in 高优先级切换

        if self.当前稳定情绪 == '执行中' and 候选情绪 in {'待机中', '调皮中', '困困的'} and 当前时间 - self.最近执行结束时间 < 8.0:
            return self.当前稳定情绪, self.当前稳定文案, self.当前来源

        if 高优先级 or 足够强 or 已停留 >= 最短停留:
            self._切换到(候选情绪, 候选文案, 候选来源, 当前时间)

        return self.当前稳定情绪, self.当前稳定文案, self.当前来源

    def _切换到(self, 情绪: str, 文案: str, 来源: str, 当前时间: float) -> None:
        if self.当前稳定情绪 == '执行中' and 情绪 != '执行中':
            self.最近执行结束时间 = 当前时间
        if 情绪 == '执行中':
            self.最近执行活跃时间 = 当前时间
        self.当前稳定情绪 = 情绪
        self.当前稳定文案 = 文案
        self.当前来源 = 来源
        self.当前情绪开始时间 = 当前时间

    def _读取消息列表(self, 会话文件: Path | None) -> list[消息片段]:
        if not 会话文件 or not 会话文件.exists():
            return []
        try:
            原始行 = 会话文件.read_text(encoding='utf-8', errors='ignore').splitlines()
        except OSError:
            return []

        结果: list[消息片段] = []
        for 行 in 原始行[-48:]:
            try:
                数据 = json.loads(行)
            except json.JSONDecodeError:
                continue
            if not isinstance(数据, dict):
                continue
            消息体 = 数据.get('message', {})
            if not isinstance(消息体, dict):
                continue
            角色 = str(消息体.get('role', 'unknown'))
            内容 = 消息体.get('content', [])
            文本, 有工具调用, 有工具结果, 工具名称, 步骤序号 = self._提取文本与工具(内容)
            if not self._是否保留消息(角色, 文本, 有工具调用, 有工具结果):
                continue
            时间戳 = self._解析时间戳(数据.get('timestamp'))
            结果.append(
                消息片段(
                    角色=角色,
                    文本=文本,
                    时间戳=时间戳,
                    有工具调用=有工具调用,
                    有工具结果=有工具结果,
                    是助手文本=角色 == 'assistant' and bool(文本),
                    是用户文本=角色 == 'user' and bool(文本),
                    工具名称=工具名称,
                    步骤序号=步骤序号,
                )
            )
        return 结果[-最近消息窗口:]

    def _提取文本与工具(self, 内容: Any) -> tuple[str, bool, bool, str, int]:
        # 忽略的工具调用（系统级工具，不应影响情绪判断）
        忽略工具 = {'cron', 'task', 'session', 'subagent', 'memory', 'heartbeat', 'exec', 'read', 'write', 'edit'}
        if isinstance(内容, str):
            return 内容.strip(), False, False, '', 0
        if not isinstance(内容, list):
            return '', False, False, '', 0
        片段: list[str] = []
        有工具调用 = False
        有工具结果 = False
        最近工具名称 = ''
        步骤序号 = 0
        for 项 in 内容:
            if not isinstance(项, dict):
                continue
            类型 = 项.get('type')
            if 类型 in {'input_text', 'output_text', 'text'}:
                文本 = 项.get('text') or 项.get('content') or ''
                if isinstance(文本, str) and 文本.strip():
                    片段.append(文本.strip())
            elif 类型 == 'toolCall':
                名称 = 项.get('toolName') or 项.get('name') or 'tool'
                if 名称.lower() in 忽略工具:
                    continue  # 跳过系统级工具调用
                有工具调用 = True
                最近工具名称 = 名称
                步骤序号 += 1  # 累加工具调用序号
                片段.append(f'[toolCall:{名称}]')
            elif 类型 == 'toolResult':
                名称 = 项.get('toolName') or 项.get('name') or 'tool'
                if 名称.lower() in 忽略工具:
                    continue  # 跳过系统级工具结果
                有工具结果 = True
                if not 最近工具名称:
                    最近工具名称 = 名称
                片段.append(f'[toolResult:{名称}]')
        return '\n'.join(片段).strip(), 有工具调用, 有工具结果, 最近工具名称, 步骤序号

    def _是否保留消息(self, 角色: str, 文本: str, 有工具调用: bool, 有工具结果: bool) -> bool:
        if not 文本 and not 有工具调用 and not 有工具结果:
            return False
        if 角色 == 'toolResult':
            return False
        噪音特征 = [
            'Successfully replaced text',
            '---状态文件---',
            '---接口---',
            '轮播序号',
            'curl -s http://127.0.0.1:8876/api/status',
            'pkill -f',
            'ps aux | grep',
            '[[reply_to_current]]',
            'Conversation info',
            '[toolCall:cron]',
            '[toolResult:cron]',
            '[toolCall:task]',
            '[toolResult:task]',
            '[toolCall:session]',
            '[toolResult:session]',
            '[toolCall:subagent]',
            '[toolResult:subagent]',
            'agent:main:cron:',
        ]
        return not any(特征 in 文本 for 特征 in 噪音特征)

    def _解析时间戳(self, 原始值: Any) -> float:
        if isinstance(原始值, (int, float)):
            return float(原始值) / 1000 if 原始值 > 10_000_000_000 else float(原始值)
        if isinstance(原始值, str):
            try:
                return time.mktime(time.strptime(原始值[:19], '%Y-%m-%dT%H:%M:%S'))
            except ValueError:
                return 0.0
        return 0.0

    def _提取更新时间(self, 会话信息: dict[str, Any]) -> float:
        原始值 = 会话信息.get('updatedAt', 0)
        if isinstance(原始值, (int, float)):
            return float(原始值) / 1000 if 原始值 > 10_000_000_000 else float(原始值)
        return 0.0

    def _构建签名(self, 快照: 会话快照) -> str:
        核心 = [
            str(int(快照.最后更新时间 or 0)),
            *(f'{项.角色}|{项.文本[-48:]}|{int(项.时间戳)}|{int(项.有工具调用)}|{int(项.有工具结果)}' for 项 in 快照.消息列表[-8:]),
        ]
        return '||'.join(核心)

    def _提取线索(self, 快照: 会话快照, 当前时间: float) -> dict[str, Any]:
        消息列表 = 快照.消息列表
        最后一条 = 快照.最后一条
        文本们 = [项.文本 for 项 in 消息列表 if 项.文本]
        合并文本 = '\n'.join(文本们)
        最近用户 = next((项 for 项 in reversed(消息列表) if 项.是用户文本), None)
        最近助手 = next((项 for 项 in reversed(消息列表) if 项.是助手文本), None)
        最近工具 = next((项 for 项 in reversed(消息列表) if 项.有工具调用 or 项.有工具结果), None)
        工具调用次数 = sum(1 for 项 in 消息列表[-8:] if 项.有工具调用)
        工具结果次数 = sum(1 for 项 in 消息列表[-8:] if 项.有工具结果)
        正向分 = self._按权重计数(消息列表, 正向关键词)
        疲惫分 = self._按权重计数(消息列表, 疲惫关键词)
        异常分 = self._按权重计数(消息列表, 异常关键词)
